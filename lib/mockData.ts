function createBroadcastNotifications(role: NotificationRoleKey): NotificationRecord[] {
  const roleLabel =
    role === "customer_service"
      ? "Customer Service"
      : role === "head_of_design"
        ? "Design"
        : role === "super_admin"
          ? "Super Admin"
          : role === "staff"
            ? "Internal Staff"
            : role.charAt(0).toUpperCase() + role.slice(1).replace(/_/g, " ");

  const important = {
    ...broadcastNotificationTemplates.important,
    id: `n-${role}-bc-001`,
    link: "/dashboard/customer/notifications",
    meta: ["From: CEO", "IMPORTANT", roleLabel],
  };

  const normal = {
    ...broadcastNotificationTemplates.normal,
    id: `n-${role}-bc-002`,
    link: "/dashboard/customer/notifications",
    meta: ["From: Operations", "Normal", roleLabel],
  };

  const notifications: NotificationRecord[] = [
    {
      ...important,
      role,
      meta: important.meta,
    },
    {
      ...normal,
      role,
      meta: normal.meta,
    },
  ];

  if (role === "customer_service" || role === "operations" || role === "technician") {
    notifications.unshift({
      ...broadcastNotificationTemplates.urgent,
      id: `n-${role}-bc-003`,
      role,
      link: "/dashboard/customer/notifications",
      meta: ["From: CEO", "URGENT", roleLabel],
    });
  }

  return notifications;
}

